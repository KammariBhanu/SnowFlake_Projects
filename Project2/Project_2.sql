);

CREATE TABLE RETAIL_DB.SALES_SCHEMA.BRANCHES(
BRANCH_ID NUMBER,
BRANCH_NAME VARCHAR(30),
CITY VARCHAR(30)
);

CREATE TABLE RETAIL_DB.SALES_SCHEMA.SALES(
SALE_ID NUMBER,
CUSTOMER_ID NUMBER,
PRODUCT_ID NUMBER,
BRANCH_ID NUMBER,
QUANTITY NUMBER,
SALE_DATE TIMESTAMP_NTZ,
TOTAL_AMOUNT NUMBER(10, 2)
);

