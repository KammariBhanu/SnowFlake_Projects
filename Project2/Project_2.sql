CREATE WAREHOUSE RETAIL_WH
WITH
    WAREHOUSE_SIZE ='XSMALL',
    AUTO_SUSPEND = 60
    AUTO_RESUME =  TRUE;

CREATE DATABASE RETAIL_DB;
CREATE SCHEMA RETAIL_DB.SALES_SCHEMA;

CREATE FILE FORMAT RETAIL_DB.SALES_SCHEMA.SALES_CSV_FORMAT
TYPE = 'CSV',
FIELD_DELIMITER = ',',
SKIP_HEADER = 1;

CREATE STAGE RETAIL_DB.SALES_SCHEMA.SALES_STAGE
FILE_FORMAT = RETAIL_DB.SALES_SCHEMA.SALES_CSV_FORMAT;

CREATE TABLE RETAIL_DB.SALES_SCHEMA.CUSTOMERS(
CUSTOMER_ID NUMBER,
CUSTOMER_NAME VARCHAR(30),
CITY VARCHAR(50),
MEMBERSHIP VARCHAR(30)
);

CREATE TABLE RETAIL_DB.SALES_SCHEMA.PRODUCTS(
PRODUCT_ID NUMBER,
PRODUCT_NAME VARCHAR(30),
CATEGORY VARCHAR(30),
