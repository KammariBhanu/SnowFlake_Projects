SELECT
    C.CUSTOMER_ID,
    C.CUSTOMER_NAME,
    SUM(S.TOTAL_AMOUNT) AS TOTAL_SPENDING,
    RANK() OVER (
        ORDER BY SUM(S.TOTAL_AMOUNT) DESC
    ) AS CUSTOMER_RANK
FROM CUSTOMERS C
JOIN SALES S
    ON C.CUSTOMER_ID = S.CUSTOMER_ID
GROUP BY
    C.CUSTOMER_ID,
    C.CUSTOMER_NAME
ORDER BY CUSTOMER_RANK;


SELECT
    B.BRANCH_ID,
    B.BRANCH_NAME,
    SUM(S.TOTAL_AMOUNT) AS TOTAL_SALES,
    RANK() OVER (
        ORDER BY SUM(S.TOTAL_AMOUNT) DESC
    ) AS BRANCH_RANK
FROM BRANCHES B
JOIN SALES S
    ON B.BRANCH_ID = S.BRANCH_ID
GROUP BY
    B.BRANCH_ID,
    B.BRANCH_NAME
ORDER BY BRANCH_RANK;



SELECT
    PRODUCT_ID,
    PRODUCT_NAME,
    CATEGORY,
    TOTAL_REVENUE
FROM (
    SELECT
        P.PRODUCT_ID,
        P.PRODUCT_NAME,
        P.CATEGORY,
        SUM(S.TOTAL_AMOUNT) AS TOTAL_REVENUE,
        ROW_NUMBER() OVER (
            PARTITION BY P.CATEGORY
            ORDER BY SUM(S.TOTAL_AMOUNT) DESC
        ) AS RN
    FROM PRODUCTS P
    JOIN SALES S
        ON P.PRODUCT_ID = S.PRODUCT_ID
    GROUP BY
        P.PRODUCT_ID,
        P.PRODUCT_NAME,
        P.CATEGORY
)
WHERE RN = 1;

SELECT
    SALE_DATE,
    SALE_ID,
    TOTAL_AMOUNT,
    SUM(TOTAL_AMOUNT) OVER (
        ORDER BY SALE_DATE
    ) AS CUMULATIVE_SALES
FROM SALES
ORDER BY SALE_DATE;

SELECT
    SALE_ID,
    SALE_DATE,
    TOTAL_AMOUNT,
    AVG(TOTAL_AMOUNT) OVER () AS AVERAGE_SALE_AMOUNT
FROM SALES
ORDER BY SALE_ID;


WITH CUSTOMER_REVENUE AS (
    SELECT
        C.CUSTOMER_ID,
        C.CUSTOMER_NAME,
        C.CITY,
        C.MEMBERSHIP,
        SUM(S.TOTAL_AMOUNT) AS TOTAL_REVENUE
    FROM RETAIL_DB.SALES_SCHEMA.CUSTOMERS C
    JOIN RETAIL_DB.SALES_SCHEMA.SALES S
        ON C.CUSTOMER_ID = S.CUSTOMER_ID
    GROUP BY
        C.CUSTOMER_ID,
        C.CUSTOMER_NAME,
        C.CITY,
        C.MEMBERSHIP
)
SELECT *
FROM CUSTOMER_REVENUE
ORDER BY TOTAL_REVENUE DESC;

WITH CUSTOMER_REVENUE AS (
    SELECT
        C.CUSTOMER_ID,
        C.CUSTOMER_NAME,
        SUM(S.TOTAL_AMOUNT) AS TOTAL_REVENUE
    FROM CUSTOMERS C
    JOIN SALES S
        ON C.CUSTOMER_ID = S.CUSTOMER_ID
    GROUP BY
        C.CUSTOMER_ID,
        C.CUSTOMER_NAME
),

AVERAGE_REVENUE AS (
    SELECT
        AVG(TOTAL_REVENUE) AS AVG_REVENUE
    FROM CUSTOMER_REVENUE
)

SELECT
    CR.CUSTOMER_ID,
    CR.CUSTOMER_NAME,
    CR.TOTAL_REVENUE,
    AR.AVG_REVENUE
FROM CUSTOMER_REVENUE CR
CROSS JOIN AVERAGE_REVENUE AR
WHERE CR.TOTAL_REVENUE > AR.AVG_REVENUE
ORDER BY CR.TOTAL_REVENUE DESC;


CREATE OR REPLACE VIEW RETAIL_DB.SALES_SCHEMA.SALES_REPORT AS
SELECT
    S.SALE_ID,
    S.SALE_DATE,
    C.CUSTOMER_ID,
    C.CUSTOMER_NAME,
    C.MEMBERSHIP,
    P.PRODUCT_ID,
    P.PRODUCT_NAME,
    P.CATEGORY,
    B.BRANCH_ID,
    B.BRANCH_NAME,
    B.CITY AS BRANCH_CITY,
    S.QUANTITY,
    P.PRICE,
    S.TOTAL_AMOUNT
FROM SALES S
JOIN CUSTOMERS C
    ON S.CUSTOMER_ID = C.CUSTOMER_ID
JOIN PRODUCTS P
    ON S.PRODUCT_ID = P.PRODUCT_ID
JOIN BRANCHES B
    ON S.BRANCH_ID = B.BRANCH_ID;


SELECT *
FROM SALES_REPORT
ORDER BY SALE_ID;


CREATE OR REPLACE VIEW RETAIL_DB.SALES_SCHEMA.TOP_CUSTOMERS AS
SELECT
    CUSTOMER_ID,
    SUM(TOTAL_AMOUNT) AS TOTAL_SPENDING
FROM RETAIL_DB.SALES_SCHEMA.SALES
GROUP BY CUSTOMER_ID;



SELECT
    CUSTOMER_ID,
    TOTAL_SPENDING
FROM RETAIL_DB.SALES_SCHEMA.TOP_CUSTOMERS
ORDER BY TOTAL_SPENDING DESC;




SELECT
    C.CUSTOMER_ID,
    C.CUSTOMER_NAME,
    C.MEMBERSHIP,
    TC.TOTAL_SPENDING
FROM RETAIL_DB.SALES_SCHEMA.TOP_CUSTOMERS TC
JOIN RETAIL_DB.SALES_SCHEMA.CUSTOMERS C
    ON TC.CUSTOMER_ID = C.CUSTOMER_ID
ORDER BY TC.TOTAL_SPENDING DESC;




SELECT
    C.CUSTOMER_ID,
